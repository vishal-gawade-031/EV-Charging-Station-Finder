// Generate an extended set of ~115 well-distributed stations
export function generateDemoStations(): ChargingStation[] {
  const stations: ChargingStation[] = [];

  SEED_TEMPLATES.forEach((tpl, index) => {
    const id = `demo-${tpl.state.toLowerCase().replace(/[^a-z0-9]/g, "").slice(0, 4)}-${String(index + 1).padStart(3, "0")}`;

    stations.push({
      id,
      name: tpl.name,
      latitude: tpl.latitude,
      longitude: tpl.longitude,
      address: `${tpl.address} (Demo fictional record for testing purposes)`,
      city: tpl.city,
      state: tpl.state,
      pincode: tpl.pincode,
      operator: tpl.operator,
      connectorTypes: tpl.connectors,
      powerKW: tpl.powerKW,
      pricing: "₹18-₹22 / kWh (Demonstration rate)",
      stationType: tpl.stationType,
      dataSource: "demo",
      isDemo: true,
      availabilityStatus: "unknown",
      lastUpdated: new Date().toISOString(),
      amenities: tpl.amenities,
      totalPorts: tpl.totalPorts,
    });
  });

  return stations;
}

